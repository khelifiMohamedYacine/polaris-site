/** Points forward in the reading direction (right in French, left in Arabic); `back` reverses it. */
export function ArrowIcon({ className = "h-4 w-4", back = false }: IconProps & { back?: boolean }) {
  return (
    <Svg className={`${className} ${back ? "-scale-x-100 rtl:scale-x-100" : "rtl:-scale-x-100"}`}>
      <path d="M5 12h14M13 6l6 6-6 6" />
    </Svg>
  );
}
